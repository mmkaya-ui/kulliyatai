"""Render ``evals/RESULTS.md`` and the README benchmark block from ``results.json``.

    python -m evals.report          # rewrite RESULTS.md and the README block
    python -m evals.report --check  # exit 1 if either is out of date (used by the tests)

Every number and every comparative sentence in those two documents is
generated here from the measured results, so the documentation cannot drift
from the data.
"""

from __future__ import annotations

import json
import sys

from rag.config import ROOT

RESULTS_JSON = ROOT / "evals" / "results" / "results.json"
RESULTS_MD = ROOT / "evals" / "RESULTS.md"
README = ROOT / "README.md"
START, END = "<!-- BENCHMARK:START (generated by `python -m evals.report`) -->", "<!-- BENCHMARK:END -->"
ALPHA = 0.05


def f3(x: float) -> str:
    return f"{x:.3f}"


def ci(m: dict) -> str:
    return f"{m['mean']:.3f} <sub>[{m['lo']:.2f}, {m['hi']:.2f}]</sub>"


def pct(m: dict) -> str:
    return f"{100 * m['mean']:.1f}% <sub>[{100 * m['lo']:.0f}, {100 * m['hi']:.0f}]</sub>"


def ms(x: float) -> str:
    return f"{x:,.0f} ms" if x >= 100 else f"{x:.1f} ms"


def settings_text(s: dict) -> str:
    return (
        f"{s['chunk_size']}/{s['chunk_overlap']} chars, header {'on' if s['contextual_header'] else 'off'}, "
        f"dense {'windows (MaxP)' if s['dense_windows'] else 'single vector'}, BM25 `{s['bm25_tokenizer']}`"
    )


def pv(p: float) -> str:
    """p-value as text; the permutation test cannot resolve values below 1/10,001."""
    return "< 0.001" if p < 0.001 else f"{p:.3f}"


def sig_word(p: float) -> str:
    return "significant" if p < ALPHA else "not significant"


def system(r: dict, name: str) -> dict | None:
    return next((s for s in r["test_systems"] if s["name"] == name), None)


def sig(r: dict, a: str, b: str, metric: str = "mrr@10") -> dict | None:
    return next((s for s in r["test_significance"] if s["a"] == a and s["b"] == b and s["metric"] == metric), None)


def main_table(r: dict) -> list[str]:
    lat = r.get("latency", {})
    rows = [
        "| System (test split) | Hit@1 | Hit@3 | Hit@5 | MRR@10 | Evidence recall@5 | Latency median / p95 |",
        "|---|---|---|---|---|---|---|",
    ]
    for s in r["test_systems"]:
        m = s["metrics"]
        row = lat.get(s["name"])
        lt = f"{ms(row['total']['median_ms'])} / {ms(row['total']['p95_ms'])}" if row else "–"
        rows.append(
            f"| **{s['name']}** | {ci(m['hit@1'])} | {ci(m['hit@3'])} | {ci(m['hit@5'])} | {ci(m['mrr@10'])} "
            f"| {ci(m['evidence_recall@5'])} | {lt} |"
        )
    return rows


def findings(r: dict) -> list[str]:
    """Data-driven bullet points (every claim is computed, not written by hand)."""
    out = []
    best = max(r["test_systems"], key=lambda s: s["metrics"]["mrr@10"]["mean"])
    out.append(
        f"Best test MRR@10: **{best['name']}** with {f3(best['metrics']['mrr@10']['mean'])} "
        f"(95% CI {best['metrics']['mrr@10']['lo']:.2f}–{best['metrics']['mrr@10']['hi']:.2f})."
    )
    for a, b in [
        ("Hybrid + rerank", "Hybrid (RRF)"),
        ("Hybrid (RRF)", "Pre-v2 settings (hybrid)"),
        ("Hybrid (RRF)", "BM25"),
        ("Hybrid (RRF)", "Dense"),
    ]:
        s = sig(r, a, b)
        if s:
            out.append(
                f"{a} vs {b}: MRR@10 {'+' if s['mean_diff'] >= 0 else ''}{s['mean_diff']:.3f}, "
                f"paired permutation p {'' if s['p_value'] < 0.001 else '= '}{pv(s['p_value'])} ({sig_word(s['p_value'])} at α = {ALPHA})."
            )
    if r.get("test_ablations"):
        worst = min(r["test_ablations"], key=lambda a: a["vs_selected"]["mean_diff"])
        out.append(
            f"Largest single-factor effect: *{worst['change']}* changes hybrid MRR@10 by "
            f"{worst['vs_selected']['mean_diff']:+.3f} (p {'' if worst['vs_selected']['p_value'] < 0.001 else '= '}{pv(worst['vs_selected']['p_value'])})."
        )
    lat = r.get("latency", {})
    if "Hybrid + rerank" in lat and "Hybrid (RRF)" in lat:
        rr = lat["Hybrid + rerank"]["stages"].get("rerank", {}).get("median_ms")
        out.append(
            f"Reranking costs {ms(rr)} median per query on {r['environment']['cpu_count']} CPU threads "
            f"({r['environment']['cpu'] or 'CPU'}); the first stage takes {ms(lat['Hybrid (RRF)']['total']['median_ms'])}."
        )
    ab = r.get("abstention")
    if ab:
        out.append(
            f"Abstention gate (no LLM): keeps {pct(ab['test_answerable_kept'])} of answerable and refuses "
            f"{pct(ab['test_unanswerable_refused'])} of unanswerable test questions "
            f"(n = {ab['n_test_unanswerable']} unanswerable; AUROC {ab['test_auroc']['reranker_top_score']:.2f})."
        )
    return out


def results_md(r: dict) -> str:
    e, p = r["environment"], r["protocol"]
    n = p["n_items"]
    L = [
        "# Benchmark results",
        "",
        "> Generated by `python -m evals.report` from [`results/results.json`](results/results.json), "
        "which `python -m evals.run` produced. Do not edit by hand: `tests/test_docs_consistency.py` fails "
        "if this file and the data disagree.",
        "",
        "## Setup",
        "",
        f"- **Corpus:** the 5 public-domain PDFs in `sample_docs/` (TR, EN, DE), manifest sha256 `{e['corpus_manifest_sha256'][:12]}…`.",
        f"- **Questions:** `evals/questions.jsonl` (sha256 `{e['questions_sha256'][:12]}…`): dev {n['dev']} "
        f"({n['dev_answerable']} answerable), test {n['test']} ({n['test_answerable']} answerable). Every answerable "
        "item has verbatim evidence that is located in the PDFs at load time; every unanswerable item lists terms "
        "verified to be absent from the corpus.",
        f"- **Relevance:** {p['relevance']}. Metrics use the top {p['depth']} results.",
        f"- **Models:** embedder `{p['embedder']}`, reranker `{p['reranker']}` (both local ONNX via FastEmbed).",
        f"- **Protocol:** all settings selected on **dev** by {p['selection_metric']}; all numbers below are "
        f"**test** unless stated. 95% CIs: percentile bootstrap over questions ({p['bootstrap_resamples']:,} "
        f"resamples). p-values: two-sided paired sign-flip permutation test ({p['permutation_resamples']:,} resamples). "
        f"RRF: k = {p['rrf_k']}, weights {p['rrf_weights']}.",
        f"- **Machine:** {e['cpu'] or 'unknown CPU'}, {e['cpu_count']} threads, Python {e['python']}, {e['platform']}. "
        f"Run time {r['runtime_s']:,.0f} s. Git commit `{(e['git_commit'] or 'n/a')[:12]}`"
        f"{' (uncommitted changes)' if e['git_dirty'] else ''}.",
        "",
        "## Main results",
        "",
        *main_table(r),
        "",
        "Selected settings (dev):",
        "",
    ]
    for mode, s in r["selected"].items():
        if isinstance(s, dict):
            L.append(f"- **{mode}:** {settings_text(s)}")
    if "rerank_candidate_k" in r["selected"]:
        L.append(f"- **reranker candidates:** {r['selected']['rerank_candidate_k']}")
    legacy = system(r, "Pre-v2 settings (hybrid)")
    if legacy:
        L.append(
            f"- **pre-v2 settings** (for comparison, not selected): {settings_text(legacy['settings'])}, "
            f"RRF weights {legacy['rrf_weights']}"
        )
    L += ["", "### Findings", "", *[f"- {x}" for x in findings(r)], ""]

    L += [
        "## Significance (test, paired)",
        "",
        "| A | B | Metric | Mean A−B | p-value | |",
        "|---|---|---|---|---|---|",
    ]
    for s in r["test_significance"]:
        L.append(
            f"| {s['a']} | {s['b']} | {s['metric']} | {s['mean_diff']:+.3f} | {pv(s['p_value'])} | {sig_word(s['p_value'])} |"
        )

    L += ["", "## By question group (test)", "", "| System | Group | n | Hit@5 | MRR@10 |", "|---|---|---|---|---|"]
    for row in r["test_breakdown"]:
        L.append(f"| {row['system']} | {row['group']} | {row['n']} | {f3(row['hit@5'])} | {f3(row['mrr@10'])} |")

    L += [
        "",
        "## One-factor ablations of the selected hybrid (test)",
        "",
        "| Change | Hit@1 | Hit@5 | MRR@10 | Δ MRR@10 vs selected | p |",
        "|---|---|---|---|---|---|",
    ]
    for a in r["test_ablations"]:
        m, v = a["metrics"], a["vs_selected"]
        L.append(
            f"| {a['change']} | {ci(m['hit@1'])} | {ci(m['hit@5'])} | {ci(m['mrr@10'])} | {v['mean_diff']:+.3f} | {pv(v['p_value'])} |"
        )

    if r.get("rerank_tradeoff"):
        L += [
            "",
            "## Reranker: candidates vs quality and latency (test)",
            "",
            "Latency measured on the first 16 answerable test questions with an uncached model.",
            "",
            "| Candidates | MRR@10 | Hit@1 | Median latency | p95 latency |",
            "|---|---|---|---|---|",
        ]
        for c in r["rerank_tradeoff"]:
            L.append(
                f"| {c['candidate_k']} | {ci(c['metrics']['mrr@10'])} | {ci(c['metrics']['hit@1'])} "
                f"| {ms(c['latency']['total']['median_ms'])} | {ms(c['latency']['total']['p95_ms'])} |"
            )

    if r.get("latency"):
        L += [
            "",
            "## Latency by stage (test, uncached, after warm-up)",
            "",
            "| System | Stage | Median | p95 |",
            "|---|---|---|---|",
        ]
        for name, v in r["latency"].items():
            for st, x in v["stages"].items():
                L.append(f"| {name} | {st} | {ms(x['median_ms'])} | {ms(x['p95_ms'])} |")

    ab = r.get("abstention")
    if ab:
        L += [
            "",
            "## Abstention without an LLM (test)",
            "",
            f"Signal: {ab['signal']}. Threshold {ab['threshold']:.3f} = {ab['threshold_rule']}.",
            "",
            "| Measure | Value |",
            "|---|---|",
            f"| Answerable questions kept | {pct(ab['test_answerable_kept'])} |",
            f"| Unanswerable questions refused (n = {ab['n_test_unanswerable']}) | {pct(ab['test_unanswerable_refused'])} |",
        ]
        for k, v in ab["test_auroc"].items():
            L.append(f"| AUROC answerable vs unanswerable, {k.replace('_', ' ')} | {v:.3f} |")
    ex = r.get("extractive")
    if ex:
        L += [
            "",
            "## Offline extractive answers (test)",
            "",
            f"Definition: {ex['definition']}.",
            "",
            "| Measure | Value |",
            "|---|---|",
            f"| Top-1 sentence is evidence | {pct(ex['top1_sentence_supports'])} |",
            f"| One of the 2 returned sentences is evidence | {pct(ex['any_of_2_sentences_supports'])} |",
            f"| End-to-end accuracy (all test items) | {pct(ex['end_to_end_test_accuracy'])} |",
            "",
            f"End-to-end: {ex['end_to_end_definition']}.",
        ]

    L += [
        "",
        "## Generated answers (LLM)",
        "",
        f"**Not measured** in this run ({r['generation']['reason']}). No refusal-rate or citation-accuracy "
        "numbers for LLM answers are claimed anywhere in this repository.",
        "",
    ]

    L += ["## Dev grid (top 5 per mode)", "", "| Mode | Settings | Hit@1 | Hit@5 | MRR@10 |", "|---|---|---|---|---|"]
    for mode in ("bm25", "dense", "hybrid"):
        rows = sorted((g for g in r["dev_grid"] if g["mode"] == mode), key=lambda g: -g["mrr@10"])[:5]
        for g in rows:
            L.append(
                f"| {mode} | {settings_text(g['settings'])} | {f3(g['hit@1'])} | {f3(g['hit@5'])} | {f3(g['mrr@10'])} |"
            )
    if r.get("dev_rerank"):
        L.append("")
        L.append(
            "Reranker candidates on dev: "
            + ", ".join(f"{d['candidate_k']} → MRR@10 {f3(d['mrr@10'])}" for d in r["dev_rerank"])
        )
    L += [
        "",
        "## Index statistics",
        "",
        "| Settings | Chunks | Dense units | Chunks truncated by the embedder |",
        "|---|---|---|---|",
    ]
    for label, st in r["index_stats"].items():
        L.append(f"| {label} | {st['n_chunks']} | {st['n_dense_units']} | {st['n_chunks_truncated_by_embedder']} |")
    L += [
        "",
        "## Reproduce",
        "",
        "```bash",
        "python -m evals.dataset     # verify the question set against the PDFs",
        "python -m evals.run         # full benchmark -> results/results.json, RESULTS.md, README block",
        "python -m evals.report --check",
        "```",
        "",
    ]
    return "\n".join(L)


def readme_block(r: dict) -> str:
    n = r["protocol"]["n_items"]
    L = [
        START,
        "",
        f"Test split: {n['test_answerable']} answerable + {n['test'] - n['test_answerable']} unanswerable questions "
        f"(settings chosen on a separate dev split of {n['dev']}). Mean with 95% bootstrap CI.",
        "",
        *main_table(r),
        "",
        *[f"- {x}" for x in findings(r)],
        "",
        "Full tables (significance tests, per-language breakdown, ablations, latency per stage, dev grid): "
        "[`evals/RESULTS.md`](evals/RESULTS.md).",
        "",
        END,
    ]
    return "\n".join(L)


def render(r: dict) -> tuple[str, str]:
    readme = README.read_text(encoding="utf-8")
    if START not in readme or END not in readme:
        raise SystemExit("README.md has no benchmark markers")
    pre, rest = readme.split(START, 1)
    _, post = rest.split(END, 1)
    return results_md(r), pre + readme_block(r) + post


def main(argv: list[str] | None = None) -> int:
    argv = sys.argv[1:] if argv is None else argv
    r = json.loads(RESULTS_JSON.read_text(encoding="utf-8"))
    md, readme = render(r)
    if "--check" in argv:
        ok_md = RESULTS_MD.read_text(encoding="utf-8") == md
        ok_readme = README.read_text(encoding="utf-8") == readme
        print("RESULTS.md:", "OK" if ok_md else "OUT OF DATE")
        print("README.md benchmark block:", "OK" if ok_readme else "OUT OF DATE")
        return 0 if ok_md and ok_readme else 1
    RESULTS_MD.write_text(md, encoding="utf-8")
    README.write_text(readme, encoding="utf-8")
    print(f"wrote {RESULTS_MD.relative_to(ROOT)} and the README benchmark block")
    return 0


if __name__ == "__main__":
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    sys.exit(main())
